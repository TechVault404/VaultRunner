ACC = {'Á': 'A', 'É': 'E', 'Í': 'I', 'Ó': 'O', 'Ú': 'U'}
CW, CH = 6, 9  # celda: 5 px de glifo + 1 de espacio; 2 filas extra arriba para acentos


def glyph(ch):
    """Matriz 5x9 (filas 0-1 = espacio para acento)."""
    rows = ['.....', '.....']
    if ch in ACC:
        rows = ['...#.', '..#..']
        base = G[ACC[ch]]
    elif ch == 'Ñ':
        rows = ['.#.#.', '#.#..']
        base = G['N']
    elif ch == 'Ü':
        rows = ['.#.#.', '.....']
        base = G['U']
    else:
        base = G[ch]
    return rows + base


CHARS = sorted(set(G) | set(ACC) | {'Ñ', 'Ü'}, key=lambda c: ord(c))


def width(ch):
    if ch == ' ':
        return 4
    g = glyph(ch)
    cols = [x for x in range(5) if any(r[x] == '#' for r in g)]
    return (max(cols) - min(cols) + 2) if cols and ch in "!¡.,:'()" else 6


def text(s, msg, x, y, color='white', shadow='black', scale=1):
    """Escribe texto en un Spr con sombra de 1 px. Devuelve el ancho dibujado."""
    cx = x
    for ch in msg.upper():
        if ch not in CHARS:
            ch = '?'
        g = glyph(ch)
        cols = [i for i in range(5) if any(r[i] == '#' for r in g)]
        off = min(cols) if (cols and ch in "!¡.,:'()") else 0
        for ry, row in enumerate(g):
            for rx, v in enumerate(row):
                if v == '#':
                    for sy in range(scale):
                        for sx in range(scale):
                            px, py = cx + (rx - off) * scale + sx, y + (ry - 2) * scale + sy
                            if shadow:
                                if s.get(px + scale, py + scale) is None or True:
                                    pass
                            s.set(px, py, color)
        cx += width(ch) * scale
    if shadow:
        pass
    return cx - x


def text_shadow(s, msg, x, y, color='white', shadow='black', scale=1):
    if shadow:
        tmp = Spr(s.w, s.h)
        text(tmp, msg, x + scale, y + scale, shadow, None, scale)
        s.paste(tmp, 0, 0)
    return text(s, msg, x, y, color, None, scale)


def measure(msg, scale=1):
    return sum(width(c if c in CHARS else '?') for c in msg.upper()) * scale


def export(path_png, path_xml):
    n = len(CHARS)
    cols = 16
    rows = (n + cols - 1) // cols
    s = Spr(cols * CW, rows * CH)
    xml = ['<?xml version="1.0"?>', '<font>',
           '  <info face="Vault5x7" size="9" bold="0" italic="0" charset="" unicode="1" stretchH="100" smooth="0" aa="0" padding="0,0,0,0" spacing="1,1"/>',
           f'  <common lineHeight="11" base="9" scaleW="{s.w}" scaleH="{s.h}" pages="1" packed="0"/>',
           '  <pages><page id="0" file="vault5x7.png"/></pages>', f'  <chars count="{n}">']
    for i, ch in enumerate(CHARS):
        gx, gy = (i % cols) * CW, (i // cols) * CH
        g = glyph(ch)
        for ry, row in enumerate(g):
            for rx, v in enumerate(row):
                if v == '#':
                    s.set(gx + rx, gy + ry, 'white')
        w = width(ch)
        cols_used = [x for x in range(5) if any(r[x] == '#' for r in g)]
        off = min(cols_used) if (cols_used and ch in "!¡.,:'()") else 0
        xml.append(f'    <char id="{ord(ch)}" x="{gx + off}" y="{gy}" width="{min(5, w)}" height="{CH}" xoffset="0" yoffset="0" xadvance="{w}" page="0" chnl="15"/>')
    xml += ['  </chars>', '</font>']
    from pix import save
    save(s, path_png)
    open(path_xml, 'w', encoding='utf-8').write('\n'.join(xml))
